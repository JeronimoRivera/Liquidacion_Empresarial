CREATE TABLE IF NOT EXISTS usuarios (
    ID_Usuario INTEGER PRIMARY KEY,
    Nombre VARCHAR(50) NOT NULL,
    Apellido VARCHAR(50) NOT NULL,
    Documento_Identidad VARCHAR(20) NOT NULL UNIQUE,
    Correo_Electronico VARCHAR(100) NOT NULL UNIQUE,
    Telefono VARCHAR(20) NOT NULL,
    Fecha_Ingreso DATE NOT NULL,
    Fecha_Salida DATE,
    Salario NUMERIC(10, 2) NOT NULL,
    Rol VARCHAR(20) NOT NULL DEFAULT 'usuario'
        CHECK (Rol IN ('administrador', 'usuario')),
    Password VARCHAR(255) NOT NULL DEFAULT 'password123'
);

CREATE TABLE IF NOT EXISTS liquidacion (
    ID_Liquidacion INTEGER PRIMARY KEY,
    Indemnizacion NUMERIC(15, 2) NOT NULL,
    Vacaciones NUMERIC(15, 2) NOT NULL,
    Cesantias NUMERIC(15, 2) NOT NULL,
    Intereses_Sobre_Cesantias NUMERIC(15, 2) NOT NULL,
    Prima_Servicios NUMERIC(15, 2) NOT NULL,
    Retencion_Fuente NUMERIC(15, 2) NOT NULL,
    Total_A_Pagar NUMERIC(15, 2) NOT NULL,
    ID_Usuario INTEGER NOT NULL,
    CONSTRAINT fk_liquidacion_usuario
        FOREIGN KEY (ID_Usuario) REFERENCES usuarios (ID_Usuario)
);

CREATE TABLE IF NOT EXISTS auditoria (
    ID_Auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Usuario_Sistema INTEGER,
    Accion VARCHAR(50) NOT NULL,
    Tabla_Afectada VARCHAR(50) NOT NULL,
    ID_Registro INTEGER,
    Datos_Anteriores TEXT,
    Datos_Nuevos TEXT,
    Fecha_Hora TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    IP_Address VARCHAR(45),
    Descripcion TEXT,
    CONSTRAINT fk_auditoria_usuario
        FOREIGN KEY (Usuario_Sistema) REFERENCES usuarios (ID_Usuario)
);

ALTER TABLE usuarios ALTER COLUMN password TYPE VARCHAR(255);
ALTER TABLE auditoria ALTER COLUMN usuario_sistema DROP NOT NULL;

CREATE INDEX IF NOT EXISTS idx_liquidacion_usuario
    ON liquidacion (ID_Usuario);
CREATE INDEX IF NOT EXISTS idx_auditoria_usuario_sistema
    ON auditoria (Usuario_Sistema);
CREATE INDEX IF NOT EXISTS idx_auditoria_fecha_hora
    ON auditoria (Fecha_Hora);
CREATE INDEX IF NOT EXISTS idx_auditoria_tabla_afectada
    ON auditoria (Tabla_Afectada);
